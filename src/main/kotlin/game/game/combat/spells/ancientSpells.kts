/**
 * The chance for a smoke spell to apply poison.
 */
val SMOKE_SPELLS_POISON_CHANCE = 1 of 8

/**
 * Iterates nearby viewable mobs of the same runtime type as the supplied victim, limited to a radius around
 * that victim.
 *
 * Both primary participants must be in multi-combat areas. At most eight secondary targets are selected, excluding
 * both participants. Each must be inside the radius, in multi-combat, attackable, and permitted by combat and
 * player-controller checks.
 *
 * @param attacker The mob casting the spell, used to validate secondary target eligibility.
 * @param victim The center mob used to determine radius, world, and runtime mob type.
 * @param radius The search radius around the victim.
 * @param action The action to perform for each matching nearby mob.
 */
inline fun <reified T : Mob> forRadiusMobs(attacker: Mob, victim: T, radius: Int, action: (Mob) -> Unit) {
    if (!attacker.inMultiArea() || !victim.inMultiArea()) return
    val area = Area.of(victim.position, radius)
    val viewable: Set<T> = world.locator.findViewable(victim.type, victim.position)
    var remaining = 8
    for (mob in viewable) {
        if (mob != victim && mob != attacker && area.contains(mob) && mob.inMultiArea() &&
            mob.combat.isAttackable && attacker.combat.checkMultiCombat(mob) &&
            (attacker !is Player || attacker.controllers.checkCombat(mob))) {
            action(mob)
            if (--remaining == 0) break
        }
    }
}

/**
 * Attempts to poison the primary victim of a smoke spell and any secondary victims reached by the spell's area effect.
 *
 * Poison is rolled independently per victim using [SMOKE_SPELLS_POISON_CHANCE]. Secondary hits check their own
 * accuracy before attempting poison; both successful hits and splashes are queued for damage delivery.
 *
 * @param victim The primary victim of the spell.
 * @param severity The poison severity to apply on a successful poison roll.
 * @param attack The active magic attack providing spell metadata and secondary-hit storage.
 */
fun poison(victim: Mob, severity: Int, attack: MagicCombatAttack<*>) {
    fun poison(mob: Mob) {
        if (rand(SMOKE_SPELLS_POISON_CHANCE)) {
            mob.status.add(PoisonStatusEffect(mob, severity))
        }
    }
    poison(victim)
    if (attack.spellEffect.radius > 0 && attack.attacker.inMultiArea()) {
        forRadiusMobs(attack.attacker, victim, attack.spellEffect.radius) {
            val hit = attack.calculateDamage(it)
            if (hit.amount.isPresent) poison(it)
            attack.damageList += hit
        }
    }
}

/**
 * Heals the attacker for one quarter of the supplied damage amount and applies the same effect to any secondary
 * targets generated by the spell.
 *
 * The heal amount is calculated as one quarter of the rolled damage capped to the victim's current health, rounded
 * down. Values below one grant no healing. This calculation precedes final defensive hooks and damage delivery.
 *
 * A player attacker is also notified that health was drained.
 *
 * @param attacker The mob receiving the healing effect.
 * @param damage The primary combat damage used to derive the initial heal amount.
 * @param attack The active magic attack providing spell metadata and secondary-hit storage.
 */
fun heal(attacker: Mob, damage: CombatDamage, attack: MagicCombatAttack<*>) {
    fun heal(dmg: CombatDamage) {
        val healAmount = floor(minOf(dmg.rawAmount, dmg.victim.health) * 0.25).toInt()
        if (healAmount < 1) {
            return
        }

        attacker.hitpoints.adjustLevel(healAmount)
    }

    heal(damage)
    if (attacker is Player) {
        attacker.sendMessage("You drain some of your opponent's health.")
    }
    if (attack.spellEffect.radius > 0 && attack.attacker.inMultiArea()) {
        forRadiusMobs(attack.attacker, attack.victim, attack.spellEffect.radius) {
            val mobDamage = attack.calculateDamage(it)
            heal(mobDamage)
            attack.damageList += mobDamage
        }
    }
}

/**
 * Applies a skill-weaken effect to the primary victim and any secondary victims reached by the spell's area effect.
 * Each secondary target must pass its own accuracy roll and has its own skill weakened.
 *
 * @param victim The primary victim of the spell.
 * @param skill The skill id to weaken.
 * @param percent The percentage of the current level to drain.
 * @param attack The active magic attack providing spell metadata and secondary-hit storage.
 */
fun weakenAll(victim: Mob, skill: Int, percent: Double, attack: MagicCombatAttack<*>) {
    weaken(victim, victim.skill(skill), percent)
    if (attack.spellEffect.radius > 0 && attack.attacker.inMultiArea()) {
        forRadiusMobs(attack.attacker, victim, attack.spellEffect.radius) {
            val hit = attack.calculateDamage(it)
            if (hit.amount.isPresent) weaken(it, it.skill(skill), percent)
            attack.damageList += hit
        }
    }
}

/**
 * Applies an immobilize effect to the primary victim and any secondary victims reached by the spell's area effect.
 * Each secondary target must pass its own accuracy roll before being immobilized.
 *
 * @param victim The primary victim of the spell.
 * @param duration How long to immobilize affected targets.
 * @param attack The active magic attack providing spell metadata and secondary-hit storage.
 */
fun immobilizeAll(victim: Mob, duration: Duration, attack: MagicCombatAttack<*>) {
    immobilize(victim, duration)
    if (attack.spellEffect.radius > 0 && attack.attacker.inMultiArea()) {
        forRadiusMobs(attack.attacker, victim, attack.spellEffect.radius) {
            val hit = attack.calculateDamage(it)
            if (hit.amount.isPresent) immobilize(it, duration)
            attack.damageList += hit
        }
    }
}

