/**
 * Plays one bounded Gnome Ball visit using native referee dialogue, passes, tackles and goal clicks.
 *
 * Banking puts away carried items and both hand slots before withdrawing owned food. Native pitch admission
 * creates the session and supplies its temporary ball; only normal game interactions advance possession or score.
 * A small read-only ownership query identifies this bot's stolen ball without tackling another player's carrier.
 * Social personalities sometimes pass to an available winger before shooting from the goal's western side.
 *
 * The visit ends after a native prize, an account-build XP cap, insufficient food, repeated interaction failures,
 * ninety seconds without possession/score progress, or the absolute deadline. Pausing releases native possession;
 * a restored attempted visit ends rather than creating a fresh match. Native departure returns earned and personal
 * balls and invalidates pending passes. No equipment, experience, score or rewards are generated by this script.
 *
 * @param bot The bot visiting the pitch.
 * @param attempted Whether the single visit has already begun.
 * @param deadline Absolute end time, retained across saves and pauses.
 * @param failures Consecutive failed interactions retained across saves.
 * @author lare96
 */
class GnomeBallBotScript(bot: Bot, private var attempted: Boolean = false,
                         private val deadline: Long = System.currentTimeMillis() + 900_000,
                         private var failures: Int = 0) : BotScript(bot) {
    companion object {
        /**
         * Native two-point tackles require a health buffer and owned food; skillers and capped Ranged builds opt out.
         * Another controller or native session is not taken over by a newly selected visit.
         */
        fun eligible(bot: Bot): Boolean = ActionSafety.NON_COMBAT.allows(bot) &&
            bot.state == EntityState.ACTIVE && !bot.inWilderness() && bot.health >= 6 &&
            BotCombatActionHandler.mayGainExperience(bot, SKILL_RANGED) &&
            bot.controllers.primary.javaClass == PlayerController::class.java && GnomeBall.session(bot) == null &&
            !bot.overlays.hasWindow() && ownsFood(bot)

        /**
         * Counts only the owned foods accepted by this visit's minimum-healing withdrawal.
         */
        private fun ownsFood(bot: Bot): Boolean = (bot.inventory.asSequence() + bot.bank.asSequence())
            .filterNotNull().any { (Food.ID_TO_FOOD[it.id]?.heal ?: 0) >= 3 }

        /**
         * Playable western stands close enough to shoot, allowing slight variation between possessions.
         */
        private val SHOOTING_STANDS = listOf(Position(2401, 3488), Position(2401, 3486), Position(2401, 3490))
    }

    /**
     * Persists the one-visit budget; transient native possession is deliberately not reconstructed.
     *
     * @author lare96
     */
    class GnomeBallData : BotScriptData() {
        /**
         * Prevents a disconnected or interrupted visit from restarting its preparation and match.
         */
        var attempted = false
        /**
         * Absolute visit deadline, including preparation and travel.
         */
        var deadline = 0L
        /**
         * Consecutive unacknowledged or unreachable gameplay interactions.
         */
        var failures = 0
        override fun load(data: JsonObject) {
            attempted = data.get("attempted").asBoolean
            deadline = data.get("deadline").asLong
            failures = data.get("failures")?.asInt ?: 0
        }
        override fun save(data: JsonObject) {
            data.addProperty("attempted", attempted)
            data.addProperty("deadline", deadline)
            data.addProperty("failures", failures)
        }
    }

    /**
     * Restores only the persisted visit budget. Native login/departure owns recovery of held or earned balls.
     */
    constructor(bot: Bot, data: GnomeBallData) : this(bot, data.attempted, data.deadline, data.failures)

    /**
     * The exact native session admitted by this visit; replacements terminate the script.
     */
    private var ownedSession: GnomeBall.Session? = null
    /**
     * Marks the travel that may create a native session, including cancellation during admission.
     */
    private var entering = false
    /**
     * Makes native departure and local cancellation idempotent.
     */
    private var cleaned = false
    /**
     * Allows at most one voluntary winger pass before the next shot.
     */
    private var passed = false
    /**
     * Last observed native game progress, used by the inactivity bound.
     */
    private var lastProgress = System.currentTimeMillis()
    /**
     * Last possession and score observation, without persisting transient native state.
     */
    private var previousState: List<Any?>? = null
    /**
     * Only the referee dialogue opened by this visit may be closed during cleanup.
     */
    private var ownedDialogue: OptionDialogue? = null
    override val allowsCombatResponse = false
    override fun allowsLoot(item: GroundItem) = false

    override suspend fun init(resumed: Boolean): Boolean {
        if (attempted || System.currentTimeMillis() >= deadline || !eligible(bot)) return true
        attempted = true
        return withTimeoutOrNull(180_000) {
            if (!handler.banking.travelToBankDepositAll() || !handler.widgets.clickCloseInterface() ||
                !handler.equipment.unequipAll() || !handler.banking.travelToBankDepositAll() ||
                !handler.banking.withdrawAnyFood(8, minimumHeal = 3)) return@withTimeoutOrNull true
            if (!handler.widgets.clickCloseInterface() || !isActionSafe()) return@withTimeoutOrNull true
            entering = true
            val arrived = handler.webWalkTo(SubZone.GNOME_BALL_PITCH)
            ownedSession = GnomeBall.session(bot)
            !arrived || !GnomeBall.inside(bot.position) || ownedSession == null
        } ?: true
    }

    /**
     * Rechecks the live session, account build and deadline during web approaches and before native clicks.
     */
    private fun canPlay(): Boolean = !cleaned && System.currentTimeMillis() < deadline && isActionSafe() &&
        GnomeBall.inside(bot.position) && GnomeBall.session(bot) === ownedSession && ownedSession != null &&
        BotCombatActionHandler.mayGainExperience(bot, SKILL_RANGED)

    /**
     * NPC discovery can extend beyond view, but only this bounded, live visit authorizes the final interaction.
     */
    private suspend fun interact(npc: Npc): Boolean = handler.interactions.approach(npc,
        timeout = 10.seconds, allowOutOfView = true) { canPlay() } &&
        handler.interactions.interact(1, npc) { canPlay() }

    /**
     * Records only native possession, flight and score transitions as progress, not repeated failed tackle clicks.
     */
    private fun observe(session: GnomeBall.Session, holder: Npc?) {
        val state = listOf(session.started, session.score, session.inPlay(), GnomeBall.hasBall(bot), holder)
        if (state != previousState) { previousState = state; lastProgress = System.currentTimeMillis() }
    }

    override suspend fun run(): Boolean {
        val session = ownedSession ?: return true
        if (!canPlay() || bot.rewardBall || failures >= 5) return true
        if (bot.health <= maxOf(5, bot.totalHealth / 2)) {
            if (!handler.inventory.eatAnyFood()) return true
            delay(1.seconds)
            return false
        }
        val holder = GnomeBall.holder(bot)
        observe(session, holder)
        if (System.currentTimeMillis() - lastProgress >= 90_000) return true
        val success: Boolean
        if (GnomeBall.hasBall(bot)) {
            val winger = if (!passed && rand(bot.personality.social * 0.3))
                world.locator.findNpcs(bot.position, 10) { it.id == 633 && GnomeBall.inside(it.position) &&
                    world.collisionManager.raycast(bot.position, it.position) }.firstOrNull() else null
            if (winger != null) {
                passed = true
                success = output.sendNpcInteraction(1, winger) && waitFor(5.seconds) { !GnomeBall.hasBall(bot) }
            } else {
                val stand = SHOOTING_STANDS.minByOrNull { it.computeLongestDistance(bot.position) }!!
                success = withTimeoutOrNull(15_000) {
                    if (!handler.webWalkTo(stand, bank = BankAccess.NONE) || !canPlay() || !GnomeBall.hasBall(bot))
                        return@withTimeoutOrNull GnomeBall.holder(bot) != null
                    val goal = world.locator.findObjects(GnomeBall.GOAL, 0) { it.id == 2393 }.firstOrNull()
                        ?: return@withTimeoutOrNull false
                    output.sendObjectInteraction(1, goal) && waitFor(5.seconds) { !GnomeBall.hasBall(bot) }
                } == true
                passed = false
            }
        } else if (holder != null && holder.baseId != 633) {
            success = interact(holder)
            delay(3.seconds)
        } else if (!session.inPlay()) {
            val referee = world.locator.findNpcs(bot.position, 30) { it.id == 635 && GnomeBall.inside(it.position) }
                .firstOrNull() ?: return true
            success = interact(referee) && waitFor(5.seconds) {
                bot.overlays[OptionDialogue::class]?.options?.contains("Play Gnome Ball") == true
            } && run {
                ownedDialogue = bot.overlays[OptionDialogue::class]
                handler.widgets.clickDialogueOption("Play Gnome Ball") && waitFor(5.seconds) { session.inPlay() }
            }
        } else {
            delay(1.seconds)
            return false
        }
        failures = if (success) 0 else failures + 1
        delay(1.seconds)
        return failures >= 5
    }

    override fun paused() {
        if (cleaned) return
        cleaned = true
        if (ownedDialogue != null && bot.overlays[OptionDialogue::class] === ownedDialogue) bot.overlays.closeWindows()
        if (entering && (ownedSession == null || GnomeBall.session(bot) === ownedSession)) GnomeBall.leave(bot)
        ownedDialogue = null
    }

    override suspend fun finish() {
        try {
            if (entering && !cleaned && GnomeBall.inside(bot.position) && bot.state == EntityState.ACTIVE && isActionSafe())
                withTimeoutOrNull(10_000) { handler.webWalkTo(GnomeBall.EXIT, bank = BankAccess.NONE) }
        } finally { paused() }
    }

    override fun snapshot() = GnomeBallData().also {
        it.attempted = attempted; it.deadline = deadline; it.failures = failures
    }
}
