    companion object {

        /**
         * A map of raw food identifiers to food.
         */
        val RAW_TO_FOOD = values().associateBy { it.raw }

        /**
         * A map of cooked food identifiers to food.
         */
        val COOKED_TO_FOOD = values().associateBy { it.cooked }
    }

    /**
     * The raw item.
     */
    val rawItem = Item(raw)

    /**
     * The cooked item.
     */
    val cookedItem = Item(cooked)

    /**
     * The burnt item.
     */
    val burntItem = Item(burnt)

    /**
     * The container handed back with the cooked or burnt product, or `null`.
     */
    val extraItem = extra?.let { Item(it) }

    /**
     * Returns `true` if this food can be cooked on the cooking object with [objectId].
     */
    fun cooksOn(objectId: Int) = when (source) {
        CookSource.ANY -> true
        CookSource.RANGE_ONLY -> objectId in Cooking.RANGES
        CookSource.FIRE_ONLY -> objectId in Cooking.FIRES
    }

    /**
     * The formatted name.
     */
    val formattedName = itemName(cooked).lowercase()
